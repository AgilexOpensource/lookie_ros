#!/usr/bin/env python3
"""Write requirements.lock.txt: the SDKs in requirements.txt pinned to exact versions.

Git requirements are pinned to a commit, PyPI requirements to ``==<version>``. Lines with a
version range (``numpy<2``) are constraints and are copied unchanged.

  --from installed  (default) versions installed in the current Python; run it in the
                    environment that was tested on the robot. Fails for SDKs installed from a
                    local directory or with uncommitted state, since those cannot be reproduced.
  --from remote     current HEAD of each git default branch and the latest PyPI release.
"""

import argparse
import json
import re
import subprocess
import sys
from datetime import date
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GIT = re.compile(r'^(?P<name>[A-Za-z0-9._-]+)\s*@\s*git\+(?P<url>[^@#\s]+?)(?:@(?P<ref>[^#\s]+))?$')
NAME = re.compile(r'^[A-Za-z0-9._-]+$')


def parse(path: Path) -> list:
    """``[(kind, name, url_or_line)]`` with kind ``git``, ``pypi`` or ``constraint``."""
    entries = []
    for raw in path.read_text(encoding='utf-8').splitlines():
        line = re.sub(r'(^|\s)#.*$', '', raw).strip()  # pip comment rule: '#' at start or after space
        if not line:
            continue
        match = GIT.match(line)
        if match:
            entries.append(('git', match['name'], match['url']))
        elif NAME.match(line):
            entries.append(('pypi', line, None))
        else:
            entries.append(('constraint', re.split(r'[<>=!~;\[ ]', line, 1)[0], line))
    return entries


def _installed(name: str):
    try:
        return metadata.distribution(name)
    except metadata.PackageNotFoundError:
        raise SystemExit(f'{name} is not installed in {sys.executable}; install it or use --from remote')


def installed_commit(name: str, url: str) -> str:
    dist = _installed(name)
    text = dist.read_text('direct_url.json')
    info = json.loads(text) if text else {}
    commit = (info.get('vcs_info') or {}).get('commit_id')
    if not commit:
        source = info.get('url', 'an unknown source')
        raise SystemExit(f'{name} {dist.version} was installed from {source}, not from a git commit; '
                         f'reinstall it with: pip install "{name} @ git+{url}@<commit>"')
    if info.get('url', '').rstrip('/').removesuffix('.git') != url.rstrip('/').removesuffix('.git'):
        print(f'warning: {name} was installed from {info.get("url")}, requirements.txt has {url}',
              file=sys.stderr)
    return commit


def remote_commit(url: str) -> str:
    out = subprocess.run(['git', 'ls-remote', url, 'HEAD'], check=True, capture_output=True,
                         text=True, timeout=60).stdout.split()
    if not out:
        raise SystemExit(f'git ls-remote {url} returned no HEAD')
    return out[0]


def latest_release(name: str) -> str:
    out = subprocess.run([sys.executable, '-m', 'pip', 'index', 'versions', name], check=True,
                         capture_output=True, text=True, timeout=120).stdout
    match = re.search(rf'^{re.escape(name)} \(([^)]+)\)', out, re.MULTILINE | re.IGNORECASE)
    if not match:
        raise SystemExit(f'cannot read the latest {name} release from pip index')
    return match.group(1)


def lock(entries: list, source: str) -> list:
    lines = []
    for kind, name, value in entries:
        if kind == 'git':
            commit = installed_commit(name, value) if source == 'installed' else remote_commit(value)
            lines.append(f'{name} @ git+{value}@{commit}')
        elif kind == 'pypi':
            version = _installed(name).version if source == 'installed' else latest_release(name)
            lines.append(f'{name}=={version}')
        else:
            lines.append(value)
    return lines


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--from', dest='source', choices=['installed', 'remote'], default='installed')
    parser.add_argument('-r', '--requirements', type=Path, default=ROOT / 'requirements.txt')
    parser.add_argument('-o', '--output', type=Path, default=ROOT / 'requirements.lock.txt')
    args = parser.parse_args(argv)

    lines = lock(parse(args.requirements), args.source)
    origin = f'installed in {sys.executable}' if args.source == 'installed' else 'remote HEAD / latest release'
    header = [f'# Generated by scripts/lock_python.py on {date.today()} from {origin}.',
              '# Install: pip install -r requirements.lock.txt. Do not edit; regenerate instead.']
    args.output.write_text('\n'.join(header + lines) + '\n', encoding='utf-8')
    print(f'wrote {args.output}', file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
