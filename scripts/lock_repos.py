#!/usr/bin/env python3
"""Pin the repositories in lookie.repos to commits (lookie.lock.repos), or check / apply the pins.

  (default)        write lookie.lock.repos from the commits checked out in this workspace's src/.
                   Run it in the workspace that was tested on the robot. Every repository must
                   be clean, and its commit must be on the branch named in lookie.repos on the
                   remote (push first), so that the pin can be cloned anywhere.
  --from remote    write lookie.lock.repos from the current remote head of each branch.
  --check          compare the checked-out commits with lookie.lock.repos; exit 1 on a difference.
  --checkout       check out the pinned commits (detached HEAD) in existing clean repositories.

New repositories are cloned with: vcs import --recursive < lookie.lock.repos
"""

import argparse
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parent
SOURCE = ROOT / 'lookie.repos'
LOCK = ROOT / 'lookie.lock.repos'
SHA = re.compile(r'^[0-9a-f]{40}$')


def load(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding='utf-8'))['repositories']


def git(repo: Path, *args: str, check: bool = True) -> str:
    result = subprocess.run(['git', '-C', str(repo), *args], capture_output=True, text=True)
    if check and result.returncode:
        raise SystemExit(f'{repo.name}: git {" ".join(args)} failed: {result.stderr.strip()}')
    return result.stdout.strip() if result.returncode == 0 else ''


def has_commit(repo: Path, commit: str) -> bool:
    return subprocess.run(['git', '-C', str(repo), 'cat-file', '-e', f'{commit}^{{commit}}'],
                          capture_output=True).returncode == 0


def same_repo(a: str, b: str) -> bool:
    """True if two clone URLs (https or ssh) name the same repository."""
    norm = lambda u: re.sub(r'^(https://|ssh://git@|git@)([^/:]+)[/:]', r'\2/', u.strip()).removesuffix('.git').lower()
    return norm(a) == norm(b)


def remote_head(url: str, branch: str, repo: Path = None) -> str:
    """Branch head on the remote; through the clone's own remote when given (it may use ssh)."""
    cmd = ['git', 'ls-remote', url, f'refs/heads/{branch}']
    if repo is not None:
        cmd = ['git', '-C', str(repo), 'ls-remote', 'origin', f'refs/heads/{branch}']
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode or not result.stdout:
        raise SystemExit(f'cannot read branch {branch} of {url}: {result.stderr.strip() or "not found"}')
    return result.stdout.split()[0]


def workspace_commit(name: str, entry: dict) -> str:
    repo = SRC / name
    if not (repo / '.git').exists():
        raise SystemExit(f'{name}: not cloned in {SRC}')
    if git(repo, 'status', '--porcelain'):
        raise SystemExit(f'{name}: has uncommitted changes; commit and push them first')
    commit = git(repo, 'rev-parse', 'HEAD')
    origin = git(repo, 'remote', 'get-url', 'origin')
    if not same_repo(origin, entry['url']):
        raise SystemExit(f'{name}: origin {origin} is not {entry["url"]}')
    tip = remote_head(entry['url'], entry['version'], repo)
    if not has_commit(repo, tip):
        raise SystemExit(f'{name}: remote head {tip[:7]} is not fetched; run git -C {repo} fetch')
    if subprocess.run(['git', '-C', str(repo), 'merge-base', '--is-ancestor', commit, tip],
                      capture_output=True).returncode:
        raise SystemExit(f'{name}: {commit[:7]} is not on {entry["version"]} at {entry["url"]}; push it first')
    return commit


def write(source: str) -> int:
    repos = load(SOURCE)
    pinned = {}
    for name, entry in repos.items():
        commit = workspace_commit(name, entry) if source == 'workspace' else \
            remote_head(entry['url'], entry['version'])
        pinned[name] = {'type': entry['type'], 'url': entry['url'], 'version': commit}
        print(f'{name:20} {commit[:12]}  ({entry["version"]})', file=sys.stderr)
    origin = f'the workspace {SRC}' if source == 'workspace' else 'the remote branch heads'
    header = (f'# Generated by scripts/lock_repos.py on {date.today()} from {origin}.\n'
              '# lookie.repos pinned to commits. Do not edit; regenerate instead.\n')
    LOCK.write_text(header + yaml.safe_dump({'repositories': pinned}, sort_keys=False), encoding='utf-8')
    print(f'wrote {LOCK}', file=sys.stderr)
    return 0


def check() -> int:
    differ = 0
    for name, entry in load(LOCK).items():
        repo = SRC / name
        current = git(repo, 'rev-parse', 'HEAD', check=False) if (repo / '.git').exists() else ''
        if current != entry['version']:
            differ += 1
            print(f'{name:20} {current[:12] or "missing":12} lock {entry["version"][:12]}')
    print('all repositories match the lock' if not differ else f'{differ} repositories differ from the lock',
          file=sys.stderr)
    return 1 if differ else 0


def checkout() -> int:
    failed = 0
    for name, entry in load(LOCK).items():
        repo, commit = SRC / name, entry['version']
        if not (repo / '.git').exists():
            print(f'{name}: missing; clone it with vcs import < lookie.lock.repos', file=sys.stderr)
            failed += 1
            continue
        if git(repo, 'rev-parse', 'HEAD') == commit:
            continue
        if git(repo, 'status', '--porcelain'):
            print(f'{name}: has uncommitted changes, left unchanged', file=sys.stderr)
            failed += 1
            continue
        if not has_commit(repo, commit):
            git(repo, 'fetch', '--quiet', 'origin', entry['version'])
        git(repo, 'checkout', '--quiet', '--detach', commit)
        print(f'{name:20} -> {commit[:12]}', file=sys.stderr)
    return 1 if failed else 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--from', dest='source', choices=['workspace', 'remote'], default='workspace')
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--checkout', action='store_true')
    args = parser.parse_args(argv)
    if args.check:
        return check()
    if args.checkout:
        return checkout()
    return write(args.source)


if __name__ == '__main__':
    sys.exit(main())
